# ======================================================================
# IMPORT LIBRARIES
# ======================================================================
from flask import Flask,render_template
# ======================================================================
# App
# ======================================================================
app=Flask(__name__)
# ======================================================================
# Home Page
# ======================================================================
@app.route("/")
def home():
    return render_template("index.html")
# ======================================================================
# Todo Page
# ======================================================================
@app.route("/todo")
def todo():
    return render_template("todos.html")
# ======================================================================
# Running App
# ======================================================================
if __name__=="__main__":
    app.run(debug=True)